"""Build Layer 2b with cross-LLM bias check via Claude Code subagents.

Companion to `build_layer2b.py`. Same output schema, same leakage filter,
but the 30% "Claude" slice is generated by dispatching Claude Code subagents
from the controller (not via the Anthropic Messages API).

Why: Claude Code OAuth tokens (`sk-ant-oat01-...`) are scoped to Claude
Code's own endpoints — Anthropic blocks them from generic Messages-API
calls (rate_limit_error). The user has a Claude Pro/Max subscription
but no `sk-ant-api03-...` API key. Using subagents lets us include
cross-LLM bias signal without a separate API key.

Three-step flow (orchestrated externally):

1. `python -m runners.build_layer2b_via_agent prepare --n-chunks 500`
   Samples chunks, splits 70/30, runs Gemini side via litellm + applies
   leakage filter, writes:
     - data/eval_queries/_layer2b_gemini.jsonl   (Gemini-tagged, filtered)
     - data/eval_queries/_pending_claude.jsonl   (raw chunks awaiting Claude)
     - data/eval_queries/_split_meta.json        (seed, sizes, model names)

2. Controller (Claude Code) reads _pending_claude.jsonl, dispatches one
   or more subagents that each generate queries for a batch of chunks
   and append JSONL records to data/eval_queries/_claude_responses.jsonl.
   Each record: {id, source_chunk_id, query}.

3. `python -m runners.build_layer2b_via_agent merge`
   Reads _claude_responses.jsonl, applies the same leakage filter
   (held-out bge-small cosine + 4-gram overlap), tags `generator: claude`,
   concatenates with _layer2b_gemini.jsonl, writes:
     - data/eval_queries/layer2b_synthetic.jsonl  (final, drop-in compat)
   Prints per-generator counts and leakage-filter stats.
"""
from __future__ import annotations
import argparse
import json
import logging
import os
import random
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from bench.leakage import is_leaky, ngram_overlap

DATA = Path(__file__).resolve().parents[1] / "data" / "eval_queries"
SAMPLE_PATH = Path(__file__).resolve().parents[1] / "data" / "chunk_samples" / "stratified_50k.parquet"

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
log = logging.getLogger(__name__)

# Same prompt as build_layer2b.py — keeps generators directly comparable.
PROMPT_TEMPLATE = """You are simulating a Singapore Family Court litigant searching through their personal evidence archive. Given the following piece of evidence, write ONE natural-sounding search query (8-20 words) that the litigant might type to find this exact piece of evidence later. The query should:

- Be casual and natural (NOT a paraphrase of the evidence)
- Mention parties or dates if relevant
- Sometimes include typos, abbreviations, or Singlish particles
- NOT directly quote the evidence

Evidence (source_type={source_type}, date={date}, party_from={party}):
\"\"\"
{chunk_text}
\"\"\"

Return ONLY the search query, nothing else."""


def _load_holdout():
    """Lazily load bge-small for leakage check (cached after first call)."""
    from sentence_transformers import SentenceTransformer
    return SentenceTransformer("BAAI/bge-small-en-v1.5", device="cuda")


def _generate_one_gemini(chunk: dict, seed: int) -> str | None:
    """Generate one query via Gemini through litellm."""
    from litellm import completion
    import litellm
    litellm.drop_params = True
    prompt = PROMPT_TEMPLATE.format(
        source_type=chunk["source_type"],
        date=chunk.get("date_sgt", "unknown"),
        party=chunk.get("party_from", "unknown"),
        chunk_text=chunk["chunk_text"][:2000],
    )
    try:
        resp = completion(
            model="gemini/gemini-2.5-flash-lite",
            messages=[{"role": "user", "content": prompt}],
            temperature=0.7,
            seed=seed,
            max_tokens=80,
        )
        return resp.choices[0].message.content.strip().strip('"').strip()
    except Exception as e:
        log.warning(f"  Gemini failed: {e}")
        return None


def _leakage_check(query: str, chunk_text: str, holdout) -> tuple[bool, str]:
    """Run held-out leakage check. Returns (leaky, reason)."""
    if ngram_overlap(query, chunk_text) > 0.6:
        return True, "ngram"
    q_emb, c_emb = holdout.encode([query, chunk_text[:2000]], normalize_embeddings=True)
    q_emb, c_emb = np.array(q_emb), np.array(c_emb)
    if is_leaky(query, chunk_text, q_emb, c_emb):
        return True, "cosine"
    return False, ""


def prepare(args: argparse.Namespace) -> None:
    """Step 1: sample + split + Gemini side + pending Claude chunks."""
    DATA.mkdir(parents=True, exist_ok=True)
    if not SAMPLE_PATH.exists():
        log.error(f"Missing corpus sample at {SAMPLE_PATH}. Run build_corpus_sample first.")
        sys.exit(1)

    log.info(f"Loading sample from {SAMPLE_PATH}...")
    sample = pd.read_parquet(SAMPLE_PATH)

    rng = random.Random(args.seed)
    n_total = min(args.n_chunks, len(sample))
    n_claude = int(round(n_total * args.claude_fraction))
    n_gemini = n_total - n_claude
    log.info(f"Split: n_total={n_total}, n_gemini={n_gemini} (70%), n_claude={n_claude} (30%)")

    picked = sample.sample(n=n_total, random_state=args.seed).reset_index(drop=True)
    claude_idx = sorted(rng.sample(range(n_total), n_claude))
    claude_mask = pd.Series([False] * n_total)
    claude_mask.iloc[claude_idx] = True
    claude_chunks = picked[claude_mask].reset_index(drop=True)
    gemini_chunks = picked[~claude_mask].reset_index(drop=True)

    # Persist pending Claude chunks for the controller to dispatch
    pending_path = DATA / "_pending_claude.jsonl"
    with pending_path.open("w") as f:
        for i, row in claude_chunks.iterrows():
            f.write(json.dumps({
                "id": f"L2b-CLAUDE-{i:05d}",
                "chunk_id": row["chunk_id"],
                "source_type": row["source_type"],
                "length_bucket": row["length_bucket"],
                "date_sgt": str(row.get("date_sgt", "")),
                "party_from": str(row.get("party_from", "")),
                "chunk_text": row["chunk_text"],
                "prompt": PROMPT_TEMPLATE.format(
                    source_type=row["source_type"],
                    date=row.get("date_sgt", "unknown"),
                    party=row.get("party_from", "unknown"),
                    chunk_text=row["chunk_text"][:2000],
                ),
            }) + "\n")
    log.info(f"Wrote {len(claude_chunks)} pending Claude chunks to {pending_path}")

    # Run Gemini side
    log.info("Loading bge-small for leakage filter...")
    holdout = _load_holdout()

    out_path = DATA / "_layer2b_gemini.jsonl"
    kept = 0
    dropped_ngram = dropped_cosine = dropped_llm = 0
    with out_path.open("w") as f:
        for i, row in gemini_chunks.iterrows():
            q = _generate_one_gemini(row.to_dict(), seed=args.seed + i)
            if not q or len(q) < 4:
                dropped_llm += 1
                continue
            leaky, reason = _leakage_check(q, row["chunk_text"], holdout)
            if leaky:
                if reason == "ngram":
                    dropped_ngram += 1
                else:
                    dropped_cosine += 1
                continue
            f.write(json.dumps({
                "id": f"L2b-GEM-{i:05d}",
                "query": q,
                "source_chunk_id": row["chunk_id"],
                "source_type": row["source_type"],
                "length_bucket": row["length_bucket"],
                "generator": "gemini",
            }) + "\n")
            kept += 1
            if (i + 1) % 50 == 0:
                log.info(f"  Gemini {i+1}/{len(gemini_chunks)}: kept={kept} dropped_llm={dropped_llm} ngram={dropped_ngram} cosine={dropped_cosine}")

    log.info(f"Gemini done: kept {kept}/{len(gemini_chunks)} (dropped_llm={dropped_llm} ngram={dropped_ngram} cosine={dropped_cosine})")

    # Meta file
    (DATA / "_split_meta.json").write_text(json.dumps({
        "seed": args.seed,
        "n_total": int(n_total),
        "n_gemini": int(n_gemini),
        "n_claude": int(n_claude),
        "gemini_model": "gemini/gemini-2.5-flash-lite",
        "claude_source": "claude-code-subagent",
    }, indent=2))


def merge(args: argparse.Namespace) -> None:
    """Step 3: leakage-filter Claude responses + merge with Gemini side."""
    DATA.mkdir(parents=True, exist_ok=True)
    pending_path = DATA / "_pending_claude.jsonl"
    responses_path = DATA / "_claude_responses.jsonl"
    gemini_path = DATA / "_layer2b_gemini.jsonl"

    if not gemini_path.exists():
        log.error(f"Missing {gemini_path}. Run `prepare` first.")
        sys.exit(1)
    if not responses_path.exists():
        log.error(f"Missing {responses_path}. Controller must populate it via subagents.")
        sys.exit(1)
    if not pending_path.exists():
        log.error(f"Missing {pending_path}. Run `prepare` first.")
        sys.exit(1)

    # Index pending chunks by id for cross-reference
    pending_by_id: dict[str, dict] = {}
    for line in pending_path.read_text().splitlines():
        if line.strip():
            r = json.loads(line)
            pending_by_id[r["id"]] = r

    log.info("Loading bge-small for leakage filter on Claude responses...")
    holdout = _load_holdout()

    claude_kept: list[dict] = []
    dropped_ngram = dropped_cosine = dropped_missing = 0
    for line in responses_path.read_text().splitlines():
        if not line.strip():
            continue
        r = json.loads(line)
        pending = pending_by_id.get(r["id"])
        if not pending:
            dropped_missing += 1
            continue
        q = r["query"].strip().strip('"').strip()
        if not q or len(q) < 4:
            dropped_missing += 1
            continue
        leaky, reason = _leakage_check(q, pending["chunk_text"], holdout)
        if leaky:
            if reason == "ngram":
                dropped_ngram += 1
            else:
                dropped_cosine += 1
            continue
        claude_kept.append({
            "id": r["id"].replace("L2b-CLAUDE-", "L2b-CLA-"),
            "query": q,
            "source_chunk_id": pending["chunk_id"],
            "source_type": pending["source_type"],
            "length_bucket": pending["length_bucket"],
            "generator": "claude",
        })

    log.info(f"Claude: kept {len(claude_kept)}, dropped_ngram={dropped_ngram} cosine={dropped_cosine} missing/empty={dropped_missing}")

    # Concatenate
    out_path = DATA / "layer2b_synthetic.jsonl"
    with out_path.open("w") as f:
        # Gemini side
        n_gem = 0
        for line in gemini_path.read_text().splitlines():
            if line.strip():
                f.write(line + "\n")
                n_gem += 1
        # Claude side
        for r in claude_kept:
            f.write(json.dumps(r) + "\n")
    log.info(f"Wrote {n_gem + len(claude_kept)} queries ({n_gem} gemini + {len(claude_kept)} claude) to {out_path}")


def main() -> None:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)

    p_prep = sub.add_parser("prepare", help="Sample + run Gemini side + write pending Claude chunks")
    p_prep.add_argument("--n-chunks", type=int, default=500)
    p_prep.add_argument("--claude-fraction", type=float, default=0.30)
    p_prep.add_argument("--seed", type=int, default=42)
    p_prep.set_defaults(func=prepare)

    p_merge = sub.add_parser("merge", help="Filter Claude responses + concatenate with Gemini side")
    p_merge.set_defaults(func=merge)

    args = ap.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
